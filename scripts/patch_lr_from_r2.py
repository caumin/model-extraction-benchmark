#!/usr/bin/env python3
"""Patch placeholder LRs in phase 3/4/5 configs after R2 sweep completes.

Behavior:
  - Aggregate R1+R2 sweep results from runs/SET-B1_random_soft_20k_seed*_sub_resnet34_*/...
  - Select best SGD variant (mean acc, tie-break by lower std) and best AdamW variant.
  - For each phase 3/4/5 config, overwrite substitute.optimizer.lr (and other LR-related
    fields) with the chosen value.

Usage:
  python3 scripts/patch_lr_from_r2.py            # dry-run, print plan
  python3 scripts/patch_lr_from_r2.py --apply    # actually edit configs
  python3 scripts/patch_lr_from_r2.py --apply --sgd-lr 0.05 --adamw-lr 1e-3  # manual override
"""
from __future__ import annotations
import argparse, glob, json, re, statistics, sys
from pathlib import Path
from typing import Optional
import yaml

ROOT = Path(__file__).resolve().parent.parent
CFG_DIR = ROOT / "configs/matrix"
RUNS = ROOT / "runs"

VARIANT_TO_LR = {
    "sgd_lr01": ("sgd", 0.01), "sgd_lr02": ("sgd", 0.02),
    "sgd_lr05": ("sgd", 0.05), "sgd_lr10": ("sgd", 0.1), "sgd_lr20": ("sgd", 0.2),
    "adamw_lr5e-4": ("adamw", 5e-4), "adamw_lr1e-3": ("adamw", 1e-3),
    "adamw_lr2e-3": ("adamw", 2e-3), "adamw_lr3e-3": ("adamw", 3e-3),
}


def collect_results() -> dict[str, list[float]]:
    results = {}
    for sjson in sorted(glob.glob(str(RUNS / "SET-B1_random_soft_20k_seed*_sub_resnet34_*/*/seed_*/summary.json"))):
        m = re.search(r"SET-B1_random_soft_20k_seed\d+_sub_resnet34_([^/]+)/", sjson)
        if not m: continue
        variant = m.group(1)
        with open(sjson) as f: d = json.load(f)
        cp = d.get("checkpoints", {}).get("20000", {}).get("track_b", {})
        acc = cp.get("acc_gt")
        if acc is not None:
            results.setdefault(variant, []).append(acc * 100)
    return results


def select_best(results: dict[str, list[float]]) -> tuple[float, float]:
    """Return (best_sgd_lr, best_adamw_lr) based on mean/std."""
    sgd_scores = []
    adamw_scores = []
    for variant, accs in results.items():
        if variant not in VARIANT_TO_LR:
            continue
        opt, lr = VARIANT_TO_LR[variant]
        m = statistics.mean(accs)
        s = statistics.stdev(accs) if len(accs) >= 2 else 0
        bucket = sgd_scores if opt == "sgd" else adamw_scores
        bucket.append((m, -s, lr, variant))  # higher mean, lower std preferred
    if not sgd_scores or not adamw_scores:
        raise SystemExit("Insufficient sweep results (need both SGD and AdamW)")
    sgd_scores.sort(reverse=True); adamw_scores.sort(reverse=True)
    print("\n=== Aggregated sweep results ===")
    print(f"{'Variant':<18} {'mean ± std':<16}  {'lr':<10}")
    for opt, scores in [("SGD", sgd_scores), ("AdamW", adamw_scores)]:
        for m, neg_s, lr, v in scores:
            print(f"  {v:<16} {m:5.2f} ± {-neg_s:5.2f}    lr={lr}")
    sgd_best = sgd_scores[0]; adamw_best = adamw_scores[0]
    print(f"\nSelected SGD: lr={sgd_best[2]} (mean={sgd_best[0]:.2f}, variant={sgd_best[3]})")
    print(f"Selected AdamW: lr={adamw_best[2]} (mean={adamw_best[0]:.2f}, variant={adamw_best[3]})")
    return sgd_best[2], adamw_best[2]


def patch_config(path: Path, sgd_lr: float, adamw_lr: float) -> str | None:
    """Patch a single config's substitute.optimizer.lr in place. Returns action label."""
    with open(path) as f:
        cfg = yaml.safe_load(f)
    opt = cfg.get("substitute", {}).get("optimizer", {})
    name = opt.get("name")
    cur_lr = opt.get("lr")
    if name == "sgd":
        if cur_lr != sgd_lr:
            opt["lr"] = sgd_lr
            return f"sgd lr {cur_lr} -> {sgd_lr}"
    elif name == "adamw":
        if cur_lr != adamw_lr:
            opt["lr"] = adamw_lr
            return f"adamw lr {cur_lr} -> {adamw_lr}"
    return None


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--sgd-lr", type=float, default=None)
    ap.add_argument("--adamw-lr", type=float, default=None)
    args = ap.parse_args()

    if args.sgd_lr is not None and args.adamw_lr is not None:
        sgd_lr, adamw_lr = args.sgd_lr, args.adamw_lr
        print(f"Using manual LRs: SGD={sgd_lr}, AdamW={adamw_lr}")
    else:
        results = collect_results()
        sgd_lr, adamw_lr = select_best(results)

    # patch all phase 3/4/5 configs (= those generated by gen_phase_rerun.py)
    targets = []
    for set_id in ("SET-A1", "SET-B1", "SET-C1"):
        for suffix in ("_adamw.yaml", "_adamw_aug.yaml", "_sub_resnet34.yaml",
                       "_sub_resnet34_aug.yaml"):
            targets.extend(CFG_DIR.glob(f"{set_id}_*{suffix}"))
    # exclude sweep configs
    targets = [p for p in targets if "_sub_resnet34_sgd_lr" not in p.name
               and "_sub_resnet34_adamw_lr" not in p.name]

    print(f"\nPatching {len(targets)} configs (apply={args.apply})")
    changed = 0
    for p in sorted(targets):
        with open(p) as f:
            cfg = yaml.safe_load(f)
        opt = cfg.get("substitute", {}).get("optimizer", {})
        name = opt.get("name")
        if name == "sgd": new_lr = sgd_lr
        elif name == "adamw": new_lr = adamw_lr
        else: continue
        cur_lr = opt.get("lr")
        if cur_lr == new_lr: continue
        changed += 1
        if args.apply:
            opt["lr"] = new_lr
            with open(p, "w") as f:
                yaml.safe_dump(cfg, f, sort_keys=False)
        print(f"  {p.name}: {name} lr {cur_lr} -> {new_lr}")

    print(f"\n{changed} configs {'patched' if args.apply else 'WOULD BE patched (use --apply)'}")


if __name__ == "__main__":
    main()
